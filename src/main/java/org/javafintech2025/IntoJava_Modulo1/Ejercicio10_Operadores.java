package org.javafintech2025.IntoJava_Modulo1;

/*
Ejercicio 5
        1. Resolver los enunciados desarrollando el código.
        2. Declarar dos variables n1=5 y n2=10.
        3. Utilizando concatenación entre las variables y los literales, mostrar en pantalla la siguiente expresión:
            a) n1 es igual a 5.
            b) n2 es igual a 10.
            c) n1 más n2 es igual a 15.
*/
public class Ejercicio10_Operadores {
    public static void main(String[] args) {
        int n1=5, n2=10;

        System.out.println("a) n1 es igual a: " + n1);
        System.out.println("b) n2 es igual a: " + n2);
        System.out.println("c) (n1+n2) es igual a: " + (n1+n2));
    }
}
